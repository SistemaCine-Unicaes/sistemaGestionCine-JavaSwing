    public models.Sala leerSala() {
        return new models.Sala(Integer.parseInt(txtCapacidad.getText().trim()),
                txtAsientosEspeciales.getText().isBlank() ? 0 : Integer.parseInt(txtAsientosEspeciales.getText().trim()),
                Integer.parseInt(txtTiempoLimpieza.getText().trim()), Integer.parseInt(txtAsientosFila.getText().trim()), "ACTIVA");
    }

    public void mostrarSala(models.Sala sala) {
        txtCapacidad.setText(Integer.toString(sala.getCapacidadTotal()));
        txtAsientosEspeciales.setText(Integer.toString(sala.getAsientosEspeciales()));
        txtTiempoLimpieza.setText(Integer.toString(sala.getTiempoDeLimpieza()));
        txtAsientosFila.setText(Integer.toString(sala.getAsientosPorFila()));
    }

    public void limpiarFormulario() {
        txtCapacidad.setText(""); txtAsientosEspeciales.setText("0");
        txtTiempoLimpieza.setText(""); txtAsientosFila.setText("");
    }

