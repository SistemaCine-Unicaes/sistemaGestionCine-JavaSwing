    public boolean isFormularioValido() {
    // Verificamos si algún campo está vacío (quitando los espacios en blanco con trim)
    if (txtCapacidad.getText().trim().isEmpty() || 
        txtTiempoLimpieza.getText().trim().isEmpty() || 
        txtAsientosFila.getText().trim().isEmpty()) {

        // Mostramos el mensaje de error
        javax.swing.JOptionPane.showMessageDialog(this, 
            "Por favor, completa todos los campos requeridos.", 
            "Error de Validación", 
            javax.swing.JOptionPane.ERROR_MESSAGE);
        return false; // Retorna falso porque el formulario tiene errores
    }
    return true; // Retorna verdadero si todo está lleno
}

